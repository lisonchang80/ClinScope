"""
FungiScope — convert a Pascal VOC detection dataset into YOLO (ultralytics) format.

Reads VOC annotations (xml) + ImageSets/Main split files and writes:
    <out>/images/{train,val,test}/<id>.jpg
    <out>/labels/{train,val,test}/<id>.txt   (one row per box: cls cx cy w h, normalized)
    <out>/data.yaml

Built for BCCD (blood cell detection) but works for any VOC-layout dataset.

Example:
    python src/prepare_yolo.py --voc-root data/BCCD_src/BCCD \
        --classes RBC WBC Platelets --out data/bccd_yolo
"""
import argparse
import shutil
import xml.etree.ElementTree as ET
from pathlib import Path


def read_split(voc_root: Path, name: str):
    f = voc_root / "ImageSets" / "Main" / f"{name}.txt"
    if not f.exists():
        return None
    return [ln.strip() for ln in f.read_text().splitlines() if ln.strip()]


def convert_one(xml_path: Path, class_to_idx: dict):
    root = ET.parse(xml_path).getroot()
    size = root.find("size")
    W = float(size.find("width").text)
    H = float(size.find("height").text)
    lines = []
    for obj in root.findall("object"):
        name = obj.find("name").text.strip()
        if name not in class_to_idx:
            continue
        b = obj.find("bndbox")
        xmin, ymin = float(b.find("xmin").text), float(b.find("ymin").text)
        xmax, ymax = float(b.find("xmax").text), float(b.find("ymax").text)
        cx = ((xmin + xmax) / 2) / W
        cy = ((ymin + ymax) / 2) / H
        w = (xmax - xmin) / W
        h = (ymax - ymin) / H
        clamp = lambda v: min(max(v, 0.0), 1.0)
        lines.append(f"{class_to_idx[name]} "
                     f"{clamp(cx):.6f} {clamp(cy):.6f} {clamp(w):.6f} {clamp(h):.6f}")
    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--voc-root", type=Path, required=True)
    ap.add_argument("--classes", nargs="+", required=True,
                    help="class names in the order that defines their indices")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--img-subdir", default="JPEGImages")
    ap.add_argument("--ann-subdir", default="Annotations")
    ap.add_argument("--img-ext", default=".jpg")
    args = ap.parse_args()

    class_to_idx = {c: i for i, c in enumerate(args.classes)}
    img_dir = args.voc_root / args.img_subdir
    ann_dir = args.voc_root / args.ann_subdir

    if args.out.exists():
        shutil.rmtree(args.out)

    totals = {}
    for split in ("train", "val", "test"):
        ids = read_split(args.voc_root, split)
        if not ids:
            continue
        (args.out / "images" / split).mkdir(parents=True, exist_ok=True)
        (args.out / "labels" / split).mkdir(parents=True, exist_ok=True)
        n_img = n_box = 0
        for id_ in ids:
            xml_path = ann_dir / f"{id_}.xml"
            img_path = img_dir / f"{id_}{args.img_ext}"
            if not xml_path.exists() or not img_path.exists():
                print(f"  [skip] missing pair for {id_}")
                continue
            lines = convert_one(xml_path, class_to_idx)
            shutil.copy2(img_path, args.out / "images" / split / img_path.name)
            (args.out / "labels" / split / f"{id_}.txt").write_text(
                "\n".join(lines), encoding="utf-8")
            n_img += 1
            n_box += len(lines)
        totals[split] = (n_img, n_box)
        print(f"[{split}] {n_img} images, {n_box} boxes")

    names_block = "\n".join(f"  {i}: {c}" for i, c in enumerate(args.classes))
    yaml = (f"# Auto-generated by prepare_yolo.py\n"
            f"path: {args.out.resolve().as_posix()}\n"
            f"train: images/train\n"
            f"val: images/val\n")
    if "test" in totals:
        yaml += "test: images/test\n"
    yaml += f"nc: {len(args.classes)}\nnames:\n{names_block}\n"
    (args.out / "data.yaml").write_text(yaml, encoding="utf-8")
    print(f"[done] wrote {args.out / 'data.yaml'}")


if __name__ == "__main__":
    main()
